"""Data for the overview map (docs/map) in the unfiltered mode: docs/map/data_all.js

Same structure as the DATA object embedded in docs/map/index.html (which holds only the 1,272 matches above the
threshold), but built from every candidate that ACT aligned in full (2,650), with no regression threshold.
The map loads it when its URL has ?data=all. Run from the repo root:  python3 pipeline/r4/map_data_all.py
"""
import os, json, statistics
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
allc = pd.read_pickle(os.path.join(ROOT, 'r3', 'lists.pkl'))['allc']
lab = pd.read_pickle(os.path.join(ROOT, 'r2', 'diag2.pkl'))[['pid', 'rank', 'rel']]
allc = allc.drop(columns=[c for c in ['rel'] if c in allc.columns]).merge(lab, on=['pid', 'rank'], how='left')
core = json.load(open(os.path.join(ROOT, '..', 'docs', 'explorer', 'core.json')))
order = [p['pid'] for p in core['passages']]; folio = {p['pid']: p['folio'] for p in core['passages']}

pids = [p for p in order if p in set(allc.pid)]
seg_i = {p: i for i, p in enumerate(pids)}
g = allc.groupby('work')
works = sorted(((w, d) for w, d in g), key=lambda kv: (-kv[1].pid.nunique(), -len(kv[1])))
work_i = {w: i for i, (w, _) in enumerate(works)}
W = [[w, d.genre.iloc[0], int(d.pid.nunique()), int(len(d)), round(statistics.median(d.S), 1), round(float(d.S.max()), 1)] for w, d in works]
M = [[seg_i[r.pid], work_i[r.work], r.ref, round(float(r.S), 2), int(r['rank']), r.rel if isinstance(r.rel, str) else '']
     for _, r in allc.sort_values(['fk', 'rank']).iterrows()]
cnt = allc.groupby('pid').size()
S = [[folio[p], p, int(cnt[p])] for p in pids]
data = dict(segs=S, works=W, matches=M, sMin=round(float(allc.S.min()), 2), sMax=round(float(allc.S.max()), 2))
out = os.path.join(ROOT, '..', 'docs', 'map', 'data_all.js')
open(out, 'w', encoding='utf-8').write('// generated by pipeline/r4/map_data_all.py: every fully aligned ACT candidate, no threshold\nwindow.DATA_ALL = '
                                        + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(S), 'segments', len(W), 'works', len(M), 'matches', 'S', data['sMin'], '…', data['sMax'], sorted({w[1] for w in W}))
